export function translate(lang: Lang, s: string): string {
  if (lang === 'ar') {
    const v = AR[s]
    if (v !== undefined) return v
  }
  return s
}

/** Translation hook — t('English source') */
export function useT() {
  const lang = usePerokioStore((s) => s.lang)
  return (s: string) => translate(lang, s)
}

/** Current language */
export function useLang(): Lang {
  return usePerokioStore((s) => s.lang)
}

/** Bilingual content picker — pick(enString, arString) */
export function usePick() {
  const lang = usePerokioStore((s) => s.lang)
  return (en: string, ar?: string) => (lang === 'ar' && ar ? ar : en)
}
